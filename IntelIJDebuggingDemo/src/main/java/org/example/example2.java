package org.example;

//Average calculation

public class example2 {
    public static void main(String[] args) {
        int m1 = 80;
        int m2 = 70;
        int m3 = 90;
        int m4 = 60;
        int m5 = 100;

        double average = m1 + m2 + m3 + m4 + m5 / 5;

        System.out.println("Student 1 Marks: " + m1);
        System.out.println("Student 2 Marks: " + m2);
        System.out.println("Student 3 Marks: " + m3);
        System.out.println("Student 4 Marks: " + m4);
        System.out.println("Student 5 Marks: " + m5);

        System.out.println("Calculated Average: " + average);
    }
}
